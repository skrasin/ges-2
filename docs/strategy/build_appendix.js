// ============ По слайду на группу ============
const TOP = 1.65;      // верх списка
const BOTTOM = 7.05;   // нижняя граница поля
const CHARS_PER_LINE = 108; // эмпирически для 14pt Arial на ширине 11.0"

GROUPS.forEach(([name, items], gi) => {
  const s = S();

  s.addText(name, {
    x: ML, y: 0.5, w: 10.0, h: 0.6,
    fontFace: FONT, fontSize: 28, color: INK, charSpacing: 0.56,
    margin: 0, isTextBox: true, valign: 'top',
  });
  s.addText(`${gi + 1} / ${GROUPS.length}`, {
    x: W - MR - 2.0, y: 0.62, w: 2.0, h: 0.3,
    fontFace: FONT, fontSize: 12, color: MUTED, align: 'right', margin: 0, isTextBox: true,
  });

  // высота строки и промежутки подбираются под количество пунктов
  const lines = items.map((t) => Math.max(1, Math.ceil(t.length / CHARS_PER_LINE)));
  const totalLines = lines.reduce((a, b) => a + b, 0);
  const avail = BOTTOM - TOP;
  const gap = items.length > 7 ? 0.14 : 0.2;
  const lineH = Math.min(0.29, (avail - gap * (items.length - 1)) / totalLines);

  let y = TOP;
  items.forEach((t, i) => {
    const h = lines[i] * lineH;
    s.addText(String(i + 1).padStart(2, '0'), {
      x: ML, y, w: 0.55, h: 0.3,
      fontFace: FONT, fontSize: 12, color: HINT, margin: 0, isTextBox: true,
    });
    s.addText(t, {
      x: ML + 0.62, y: y - 0.02, w: 11.0, h: h + 0.08,
      fontFace: FONT, fontSize: 14, color: INK, margin: 0, isTextBox: true,
      lineSpacingMultiple: 1.15, valign: 'top',
    });
    y += h + gap;
    if (i < items.length - 1) {
      s.addShape(pres.ShapeType.line, {
        x: ML, y: y - gap / 2, w: CW, h: 0, line: { color: HAIR, width: 0.75 },
      });
    }
  });

  s.addNotes(`${name}: ${items.length} пунктов.`);
});

